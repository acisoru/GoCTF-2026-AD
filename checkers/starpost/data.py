def company():
    return {"name": random.choice(COMPANIES) + " " + rnd_string(4), "tax_id": str(random.randint(1000000000, 9999999999))}


def product(cargo):
    name, description = random.choice(PRODUCTS)
    return {"name": f"{name} {rnd_string(4).upper()}", "description": description, "price": random.randint(101, 180), "cargo": cargo}


def public_review():
    return random.choice(PUBLIC_REVIEWS)


def manifest(flag=None):
    reference = flag or ("MANIFEST-" + rnd_string(18).upper())
    return f"Опломбированный груз. Выдать только владельцу заказа. Код грузового манифеста: {reference}"
